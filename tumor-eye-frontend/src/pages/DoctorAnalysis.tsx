function Slider({
  sliderKey,
  label,
  value,
  min,
  max,
  onBeginChange,
  onFinishChange,
  onChange,
}: {
  sliderKey: keyof Adjustments;
  label: string;
  value: number;
  min: number;
  max: number;
  onBeginChange: (key: keyof Adjustments) => void;
  onFinishChange: () => void;
  onChange: (key: keyof Adjustments, value: number) => void;
}) {
  return (
    <label className="block w-[232px]">
      <span
        className="block text-[17px] font-extrabold mb-[8px]"
        style={{ color: "var(--c-sidebar-text)" }}
      >
        {label}
      </span>

      <input
        type="range"
        min={min}
        max={max}
        value={value}
        onPointerDown={() => onBeginChange(sliderKey)}
        onPointerUp={onFinishChange}
        onMouseUp={onFinishChange}
        onTouchEnd={onFinishChange}
        onBlur={onFinishChange}
        onKeyDown={(event) => {
          if (
            event.key === "ArrowLeft" ||
            event.key === "ArrowRight" ||
            event.key === "ArrowUp" ||
            event.key === "ArrowDown"
          ) {
            onBeginChange(sliderKey);
          }
        }}
        onKeyUp={onFinishChange}
        onChange={(event) => onChange(sliderKey, Number(event.target.value))}
        className="w-[232px] h-[9px] cursor-pointer"
        style={{
          accentColor: "#4a7c73",
        }}
      />
    </label>
  );
}

