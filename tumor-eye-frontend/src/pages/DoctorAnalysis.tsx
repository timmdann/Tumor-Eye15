import { useEffect, useRef, useState, type ReactNode } from "react";
import { useLocation, useNavigate } from "react-router-dom";
import { jsPDF } from "jspdf";
import AppPanelLayout from "@/components/AppPanelLayout";

type Step = "upload" | "adjust" | "analyzing" | "result";

type Adjustments = {
  brightness: number;
  contrast: number;
  sharpness: number;
};

type LocationState = {
  openResult?: boolean;
};

const DEFAULT_ADJUSTMENTS: Adjustments = {
  brightness: 100,
  contrast: 100,
  sharpness: 100,
};

export default function DoctorAnalysis() {
  const [step, setStep] = useState<Step>("upload");
  const [imageUrl, setImageUrl] = useState<string | null>(null);
  const [adjustments, setAdjustments] =
    useState<Adjustments>(DEFAULT_ADJUSTMENTS);

  const [history, setHistory] = useState<Adjustments[]>([]);
  const activeEditRef = useRef<keyof Adjustments | null>(null);

  const navigate = useNavigate();
  const location = useLocation();

  useEffect(() => {
    const state = location.state as LocationState | null;

    if (!state?.openResult) return;

    const storedImageUrl = sessionStorage.getItem("doctorChatImageUrl");

    if (storedImageUrl) {
      setImageUrl(storedImageUrl);
      setStep("result");
    }
  }, [location.state]);

  useEffect(() => {
    if (step !== "analyzing") return;

    const timer = window.setTimeout(() => {
      setStep("result");
    }, 5000);

    return () => window.clearTimeout(timer);
  }, [step]);

  function handleUpload(file: File) {
    const reader = new FileReader();

    reader.onload = () => {
      const result = reader.result;

      if (typeof result !== "string") return;

      setImageUrl(result);
      setAdjustments(DEFAULT_ADJUSTMENTS);
      setHistory([]);
      activeEditRef.current = null;
      setStep("adjust");
    };

    reader.readAsDataURL(file);
  }

  function handleNewScan() {
    sessionStorage.removeItem("doctorChatImageUrl");
    sessionStorage.removeItem("doctorChatImageFilter");

    setImageUrl(null);
    setAdjustments(DEFAULT_ADJUSTMENTS);
    setHistory([]);
    activeEditRef.current = null;
    setStep("upload");
  }

  function handleBackToUpload() {
    sessionStorage.removeItem("doctorChatImageUrl");
    sessionStorage.removeItem("doctorChatImageFilter");

    setImageUrl(null);
    setAdjustments(DEFAULT_ADJUSTMENTS);
    setHistory([]);
    activeEditRef.current = null;
    setStep("upload");

    navigate("/doctor/upload", { replace: true, state: null });
  }

  function beginAdjustment(key: keyof Adjustments) {
    if (activeEditRef.current === key) return;

    activeEditRef.current = key;
    setHistory((prev) => [...prev, adjustments]);
  }

  function finishAdjustment() {
    activeEditRef.current = null;
  }

  function updateAdjustment(key: keyof Adjustments, value: number) {
    setAdjustments((prev) => ({
      ...prev,
      [key]: value,
    }));
  }

  function resetAdjustments() {
    setHistory((prev) => [...prev, adjustments]);
    activeEditRef.current = null;
    setAdjustments(DEFAULT_ADJUSTMENTS);
  }

  function undoAdjustments() {
    setHistory((prev) => {
      if (prev.length === 0) return prev;

      const lastAdjustment = prev[prev.length - 1];
      setAdjustments(lastAdjustment);

      return prev.slice(0, -1);
    });

    activeEditRef.current = null;
  }

  function sendForAnalysis() {
    activeEditRef.current = null;
    setStep("analyzing");
  }

  function recalculateAnalysis() {
    setStep("analyzing");
  }

  const sharpnessBoost = adjustments.sharpness - 100;

  const imageFilter = `
    brightness(${adjustments.brightness + sharpnessBoost * 0.08}%)
    contrast(${adjustments.contrast + sharpnessBoost * 0.45}%)
  `;

  async function savePdf() {
    if (!imageUrl) return;

    const reportImage = await createReportImage(imageUrl, imageFilter);

    const pdf = new jsPDF({
      orientation: "portrait",
      unit: "mm",
      format: "a4",
    });

    pdf.setTextColor(16, 33, 36);

    pdf.setFont("times", "bold");
    pdf.setFontSize(28);
    pdf.text("MRI Scan Review", 22, 26);

    pdf.setDrawColor(74, 124, 115);
    pdf.setLineWidth(0.3);
    pdf.line(22, 36, 82, 36);

    pdf.setFontSize(14);
    pdf.text("Detected suspicious regions: 1", 22, 51);
    pdf.text("Region 1: tumor, confidence 84.2%", 22, 62);

    pdf.setFontSize(10);
    pdf.text(
      "Note: this result does not constitute a medical diagnosis.",
      22,
      78
    );

    pdf.addImage(reportImage, "PNG", 22, 94, 125, 125);

    pdf.setFont("times", "normal");
    pdf.setFontSize(9);
    pdf.setTextColor(90, 90, 90);
    pdf.text("Generated by Tumor Eye'15.", 22, 235);

    pdf.save("mri-scan-review.pdf");
  }

  if (step === "analyzing") {
    return <AnalyzingScreen />;
  }

  return (
    <AppPanelLayout
      showBack={step !== "upload"}
      showLogout={step === "upload"}
      onBack={handleBackToUpload}
      title={
        step === "upload"
          ? "AI-Assisted MRI Brain Analysis"
          : step === "adjust"
          ? "Image Adjustments"
          : "MRI Scan Review"
      }
      subtitle={
        step === "upload"
          ? "Upload a brain MRI scan and generate a structured AI-supported radiology analysis."
          : undefined
      }
      sidebarContent={
        step === "adjust" ? (
          <AdjustmentsPanel
            adjustments={adjustments}
            onBeginChange={beginAdjustment}
            onFinishChange={finishAdjustment}
            onChange={updateAdjustment}
            onUndo={undoAdjustments}
            onReset={resetAdjustments}
            onSend={sendForAnalysis}
          />
        ) : step === "result" ? (
          <ResultSidebar
            onNewScan={handleNewScan}
            onRecalculate={recalculateAnalysis}
            onSavePdf={savePdf}
            onChat={() => {
              if (imageUrl) {
                sessionStorage.setItem("doctorChatImageUrl", imageUrl);
                sessionStorage.setItem("doctorChatImageFilter", imageFilter);
              }

              navigate("/doctor/chat", {
                state: {
                  imageUrl,
                  imageFilter,
                },
              });
            }}
          />
        ) : undefined
      }
    >
      {step === "upload" ? (
        <UploadArea onUpload={handleUpload} />
      ) : (
        <ImagePreview
          imageUrl={imageUrl}
          imageFilter={imageFilter}
          showDetection={step === "result"}
        />
      )}
    </AppPanelLayout>
  );
}

async function createReportImage(imageUrl: string, imageFilter: string) {
  const img = await loadImage(imageUrl);

  const canvas = document.createElement("canvas");
  canvas.width = 430;
  canvas.height = 430;

  const ctx = canvas.getContext("2d");

  if (!ctx) {
    throw new Error("Could not create canvas context.");
  }

  ctx.fillStyle = "#000000";
  ctx.fillRect(0, 0, canvas.width, canvas.height);

  const scale = Math.min(canvas.width / img.width, canvas.height / img.height);
  const drawWidth = img.width * scale;
  const drawHeight = img.height * scale;
  const drawX = (canvas.width - drawWidth) / 2;
  const drawY = (canvas.height - drawHeight) / 2;

  ctx.filter = imageFilter.replace(/\s+/g, " ").trim();
  ctx.drawImage(img, drawX, drawY, drawWidth, drawHeight);
  ctx.filter = "none";

  const boxX = canvas.width * 0.385;
  const boxY = canvas.height * 0.245;
  const boxW = canvas.width * 0.14;
  const boxH = canvas.height * 0.125;

  ctx.fillStyle = "#00ff38";
  ctx.fillRect(boxX, boxY - 22, 94, 22);

  ctx.fillStyle = "#102124";
  ctx.font = "bold 16px Georgia, serif";
  ctx.fillText("tumor 84%", boxX + 7, boxY - 7);

  ctx.strokeStyle = "#00ff38";
  ctx.lineWidth = 4;
  ctx.strokeRect(boxX, boxY, boxW, boxH);

  return canvas.toDataURL("image/png");
}

function loadImage(src: string) {
  return new Promise<HTMLImageElement>((resolve, reject) => {
    const img = new Image();

    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error("Could not load image."));
    img.src = src;
  });
}

